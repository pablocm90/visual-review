import { describe, expect, test } from 'vitest';
import type { Lockfile } from '../core/lockfile.ts';
import { bundlerLockfile } from './bundler.ts';
import { cargoLockfile } from './cargo.ts';
import { npmLockfile } from './npm.ts';
import { pnpmLockfile } from './pnpm.ts';
import { yarnLockfile } from './yarn.ts';

const reading = (lockfile: Lockfile, text: string) => {
  const { versions, direct } = lockfile.read({ text, manifests: [] });
  return { versions: Object.fromEntries(versions), direct: [...direct].toSorted() };
};

describe('Cargo.lock', () => {
  const read = (text: string) => reading(cargoLockfile, text);
  const registry = 'source = "registry+https://github.com/rust-lang/crates.io-index"';

  test('locks what comes from a source, and what a local package depends on is direct', () => {
    expect(
      read(`# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "application"
version = "0.1.1"
dependencies = [
 "itoa 1.0.15",
 "models",
 "serde",
 "url 2.5.8 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "itoa"
version = "1.0.15"
${registry}
checksum = "4a5f13b858c8d314ee3e8f639011f7ccefe71f97f96e50151fb991f267928e2c"

[[package]]
name = "models"
version = "0.1.1"

[[package]]
name = "ryu"
version = "1.0.20"
${registry}

[[package]]
name = "serde"
version = "1.0.219"
${registry}
dependencies = [
 "ryu",
]

[[package]]
name = "url"
version = "2.5.8"
source = "git+https://example.com/url#abc123"
`),
    ).toEqual({
      versions: {
        itoa: ['1.0.15'],
        ryu: ['1.0.20'],
        serde: ['1.0.219'],
        url: ['2.5.8'],
      },
      direct: ['itoa', 'models', 'serde', 'url'],
    });
  });

  test('a name locked at several versions holds each once', () => {
    expect(
      read(`[[package]]
name = "itoa"
version = "1.0.15"
${registry}

[[package]]
name = "itoa"
version = "1.0.15"
source = "git+https://example.com/itoa#abc123"

[[package]]
name = "itoa"
version = "1.0.9"
${registry}
`).versions,
    ).toEqual({ itoa: ['1.0.9', '1.0.15'] });
  });

  test('an unused patch after the last package is no package', () => {
    expect(
      read(`[[package]]
name = "application"
version = "0.1.1"

[[patch.unused]]
name = "itoa"
version = "1.0.15"
${registry}
`).versions,
    ).toEqual({});
  });

  test.for([
    { what: 'a symlink', text: '../shared/Cargo.lock' },
    { what: 'an empty file', text: '' },
  ])('$what is not read, and the message quotes none of it', ({ text }) => {
    expect(() => read(text)).toThrow(new Error('format not recognised'));
  });

  const crate = 'name = "evil"\nversion = "1.0.0"';
  test.for([
    { what: 'a single-quoted source', text: `[[package]]\n${crate}\nsource = 'registry+x'\n` },
    { what: 'an indented source', text: `[[package]]\n${crate}\n  source = "registry+x"\n` },
    { what: 'a source with no spaces', text: `[[package]]\n${crate}\nsource="registry+x"\n` },
    { what: 'a quoted key', text: `[[package]]\n${crate}\n"source" = "registry+x"\n` },
    { what: 'a package with no name', text: '[[package]]\nversion = "1.0.0"\n' },
    { what: 'a package with no version', text: '[[package]]\nname = "evil"\n' },
    {
      what: 'an indented header',
      text: `[[package]]\n${crate}\nsource = "registry+x"\n\n[metadata]\n  [[package]]\n${crate}\n`,
    },
    { what: 'a spaced header', text: `[[package]]\n${crate}\n\n[[ package ]]\n${crate}\n` },
    {
      what: 'packages written as an inline array',
      text: `package = [{ name = "evil" }]\n\n[[package]]\n${crate}\n`,
    },
  ])('$what, which cargo reads but this reader would misread, is not read', ({ text }) => {
    expect(() => read(text)).toThrow(new Error('format not recognised'));
  });

  test('an older lockfile, with a replacement and checksums in its metadata, is read', () => {
    expect(
      read(`[[package]]
name = "itoa"
version = "1.0.15"
${registry}
replace = "itoa 1.0.15 (git+https://example.com/itoa#abc123)"

[[package]]
name = "serde"
version = "1.0.219"
${registry}
dependencies = []

[metadata]
"checksum itoa 1.0.15 (registry+https://example.com)" = "4a5f"
`).versions,
    ).toEqual({ itoa: ['1.0.15'], serde: ['1.0.219'] });
  });
});

