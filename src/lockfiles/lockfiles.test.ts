import { describe, expect, test } from 'vitest';
import type { Lockfile } from '../core/lockfile.ts';
import { bundlerLockfile } from './bundler.ts';
import { cargoLockfile } from './cargo.ts';

const reading = (lockfile: Lockfile, text: string) => {
  const { versions, direct } = lockfile.read({ text, manifests: [] });
  return { versions: Object.fromEntries(versions), direct: [...direct].toSorted() };
};

describe('Cargo.lock', () => {
  const read = (text: string) => reading(cargoLockfile, text);
  const registry = 'source = "registry+https://github.com/rust-lang/crates.io-index"';

  test('locks what comes from a source, and what a local package depends on is direct', () => {
    expect(
      read(`# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "application"
version = "0.1.1"
dependencies = [
 "itoa 1.0.15",
 "models",
 "serde",
 "url 2.5.8 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "itoa"
version = "1.0.15"
${registry}
checksum = "4a5f13b858c8d314ee3e8f639011f7ccefe71f97f96e50151fb991f267928e2c"

[[package]]
name = "models"
version = "0.1.1"

[[package]]
name = "ryu"
version = "1.0.20"
${registry}

[[package]]
name = "serde"
version = "1.0.219"
${registry}
dependencies = [
 "ryu",
]

[[package]]
name = "url"
version = "2.5.8"
source = "git+https://example.com/url#abc123"
`),
    ).toEqual({
      versions: {
        itoa: ['1.0.15'],
        ryu: ['1.0.20'],
        serde: ['1.0.219'],
        url: ['2.5.8'],
      },
      direct: ['itoa', 'models', 'serde', 'url'],
    });
  });

  test('a name locked at several versions holds each once', () => {
    expect(
      read(`[[package]]
name = "itoa"
version = "1.0.15"
${registry}

[[package]]
name = "itoa"
version = "1.0.15"
source = "git+https://example.com/itoa#abc123"

[[package]]
name = "itoa"
version = "1.0.9"
${registry}
`).versions,
    ).toEqual({ itoa: ['1.0.9', '1.0.15'] });
  });

  test('an unused patch after the last package is no package', () => {
    expect(
      read(`[[package]]
name = "application"
version = "0.1.1"

[[patch.unused]]
name = "itoa"
version = "1.0.15"
${registry}
`).versions,
    ).toEqual({});
  });

  test.for([
    { what: 'a symlink', text: '../shared/Cargo.lock' },
    { what: 'an empty file', text: '' },
  ])('$what is not read, and the message quotes none of it', ({ text }) => {
    expect(() => read(text)).toThrow(/^Cargo\.lock format not recognised$/);
  });
});

describe('Gemfile.lock', () => {
  const read = (text: string) => reading(bundlerLockfile, text);

  test('locks the gems of its remote sources, each platform of one as one version', () => {
    expect(
      read(`GIT
  remote: https://example.com/ponto.git
  revision: abc123
  specs:
    ponto (2.1.0)
      faraday (>= 1.0)

PATH
  remote: engines/billing
  specs:
    billing (0.3.0)
      nokogiri

GEM
  remote: https://rubygems.org/
  specs:
    faraday (2.14.0)
    nokogiri (1.19.4)
    nokogiri (1.19.4-aarch64-linux-gnu)
    nokogiri (1.19.4-java)
    rspec-rails (8.0.0.rc1)

PLUGIN SOURCE
  remote: https://example.com/plugin
  type: example
  specs:
    plugged (1.2.0)

PLATFORMS
  ruby
  x86_64-linux

DEPENDENCIES
  billing!
  nokogiri (>= 1.18)
  ponto!
  rspec-rails

CHECKSUMS
  faraday (2.14.0) sha256=abc
    unchecked (9.9.9)

RUBY VERSION
   ruby 3.3.5p100

BUNDLED WITH
   2.6.2
`),
    ).toEqual({
      versions: {
        faraday: ['2.14.0'],
        nokogiri: ['1.19.4'],
        plugged: ['1.2.0'],
        ponto: ['2.1.0'],
        'rspec-rails': ['8.0.0.rc1'],
      },
      direct: ['billing', 'nokogiri', 'ponto', 'rspec-rails'],
    });
  });

  test('a text with no dependencies section is not read, and the message quotes none of it', () => {
    expect(() => read('../shared/Gemfile.lock')).toThrow(/^Gemfile\.lock format not recognised$/);
  });
});
